"""Face-validity check for the sentiment lexicon.

    python -m experiments.sentiment_face_validity

BANKING77 has no sentiment labels, so sentiment accuracy cannot be measured.
What *can* be checked is whether the scorer behaves the way an unlabelled
dataset still lets us predict it should: intents that are complaints by
construction ("card_swallowed", "compromised_card") ought to score more
negatively than intents that are neutral questions by construction
("exchange_rate", "visa_or_mastercard").

If that ordering did not hold, the scorer would be broken. That it does hold is
weak evidence that it is not broken. It is **not** evidence that the scores are
accurate, calibrated, or safe to threshold on, and the report says so.

The output is descriptive statistics, not a metric. Nothing here belongs in a
headline table.
"""

from __future__ import annotations

import argparse
import json
import logging
from typing import Dict, List

import numpy as np

from src.config import RESULTS_DIR, ensure_dirs
from src.extraction.intent import classify_speech_act
from src.extraction.sentiment import score_many
from src.logging_setup import configure
from src.models.data import load_split
from src.taxonomy import load_taxonomy

LOGGER = logging.getLogger("sentiment")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--split", default="test", choices=("val", "test"))
    args = parser.parse_args(argv)

    configure()
    ensure_dirs()
    taxonomy = load_taxonomy()
    frame = load_split(args.split)

    scores = score_many(frame["text"].tolist())
    frame = frame.assign(
        compound=[s.compound for s in scores],
        sentiment_label=[s.label for s in scores],
        speech_act=[classify_speech_act(t) for t in frame["text"]],
    )

    def group(column: str) -> List[Dict[str, object]]:
        rows = []
        for key, chunk in frame.groupby(column):
            rows.append({
                column: str(key),
                "n": int(len(chunk)),
                "mean_compound": round(float(chunk["compound"].mean()), 4),
                "median_compound": round(float(chunk["compound"].median()), 4),
                "negative_share": round(
                    float((chunk["sentiment_label"] == "negative").mean()), 4),
            })
        return sorted(rows, key=lambda r: r["mean_compound"])

    by_category = group("category")
    by_intent = group("intent")
    by_act = group("speech_act")

    payload = {
        "split": args.split,
        "n_rows": int(len(frame)),
        "overall_mean_compound": round(float(frame["compound"].mean()), 4),
        "overall_label_mix": {
            label: round(float((frame["sentiment_label"] == label).mean()), 4)
            for label in ("negative", "neutral", "positive")
        },
        "by_category": by_category,
        "by_speech_act": by_act,
        "most_negative_intents": by_intent[:10],
        "most_positive_intents": by_intent[-10:][::-1],
        "caveat": (
            "descriptive only; the dataset has no sentiment labels so no "
            "accuracy, precision or recall can be computed"
        ),
    }

    # Rank correlation between category mean sentiment and category base
    # priority. A negative correlation means the categories the business treats
    # as urgent are also the ones customers write about most negatively, which
    # is the direction the routing rules assume.
    priorities = np.array(
        [taxonomy.categories[r["category"]].base_priority for r in by_category]
    )
    means = np.array([r["mean_compound"] for r in by_category])
    if len(set(priorities.tolist())) > 1:
        payload["priority_sentiment_correlation"] = round(
            float(np.corrcoef(priorities, means)[0, 1]), 4
        )

    lines = [
        "<!-- GENERATED by `python -m experiments.sentiment_face_validity` -->\n",
        "# Sentiment: face validity, not accuracy\n\n",
        f"**{args.split}** split, {len(frame)} records.\n\n",
        "> BANKING77 carries no sentiment labels. Everything below is a "
        "descriptive statistic. There is no accuracy figure here because there "
        "is nothing to compute one against. Do not quote these numbers as "
        "sentiment performance.\n\n",
        f"Overall mean compound score: **{payload['overall_mean_compound']:+.4f}**. "
        f"Label mix: {payload['overall_label_mix']}.\n\n",
        "## By triage category\n\n",
        "| Category | n | Mean compound | Median | Negative share |\n",
        "| --- | ---: | ---: | ---: | ---: |\n",
    ]
    for row in by_category:
        lines.append(
            f"| `{row['category']}` | {row['n']} | {row['mean_compound']:+.4f} "
            f"| {row['median_compound']:+.4f} | {row['negative_share']:.4f} |\n"
        )

    lines.append("\n## Ten most negative intents\n\n| Intent | n | Mean compound |\n")
    lines.append("| --- | ---: | ---: |\n")
    for row in payload["most_negative_intents"]:
        lines.append(f"| `{row['intent']}` | {row['n']} | {row['mean_compound']:+.4f} |\n")

    lines.append("\n## Ten most positive intents\n\n| Intent | n | Mean compound |\n")
    lines.append("| --- | ---: | ---: |\n")
    for row in payload["most_positive_intents"]:
        lines.append(f"| `{row['intent']}` | {row['n']} | {row['mean_compound']:+.4f} |\n")

    lines.append("\n## By rule-derived speech act\n\n| Speech act | n | Mean compound | Negative share |\n")
    lines.append("| --- | ---: | ---: | ---: |\n")
    for row in by_act:
        lines.append(
            f"| `{row['speech_act']}` | {row['n']} | {row['mean_compound']:+.4f} "
            f"| {row['negative_share']:.4f} |\n"
        )

    if "priority_sentiment_correlation" in payload:
        lines.append(
            f"\nCorrelation between a category's base priority number and its mean "
            f"sentiment: **{payload['priority_sentiment_correlation']:+.4f}**. "
            "Priority 1 is most urgent, so a positive correlation here means the "
            "urgent categories score more negatively, which is the direction the "
            "routing rules assume.\n"
        )

    (RESULTS_DIR / "sentiment_face_validity.json").write_text(
        json.dumps(payload, indent=2), encoding="utf-8")
    (RESULTS_DIR / "sentiment_face_validity.md").write_text(
        "".join(lines), encoding="utf-8")
    LOGGER.info("wrote %s", RESULTS_DIR / "sentiment_face_validity.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
