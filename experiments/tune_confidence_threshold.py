"""Choose the auto-routing confidence threshold on the validation split.

    python -m experiments.tune_confidence_threshold

The threshold decides which records the service routes automatically and which
it holds for a human. Picking it by eye is how you end up with a number nobody
can defend, so it is picked against an explicit cost model:

    cost = MISROUTE_COST * (auto-routed records that were wrong)
         +                 (records held for review)

with ``MISROUTE_COST`` saying how many manual reviews one wrong auto-route is
worth. The default of 5 is an assumption about the business, not a fact about
the data, and it is the first thing to change if the operating point looks
wrong. The sweep is printed in full so a different assumption can be read
straight off the table.

Validation, never test: the threshold is a fitted parameter like any other.
"""

from __future__ import annotations

import argparse
import json
import logging
from typing import Dict, List

import numpy as np

from src.config import RESULTS_DIR, ROUTING_POLICY_PATH, ensure_dirs
from src.logging_setup import configure
from src.models.data import load_split
from src.models.registry import ModelRegistry

LOGGER = logging.getLogger("threshold")

MISROUTE_COST = 5.0
THRESHOLDS = [round(x, 2) for x in np.arange(0.0, 0.96, 0.05)]


def sweep(confidence: np.ndarray, correct: np.ndarray) -> List[Dict[str, float]]:
    n = len(confidence)
    rows = []
    for threshold in THRESHOLDS:
        auto = confidence >= threshold
        n_auto = int(auto.sum())
        errors = int((auto & ~correct).sum())
        held = n - n_auto
        rows.append({
            "threshold": threshold,
            "auto_route_rate": round(n_auto / n, 4),
            "held_for_review": held,
            "auto_routed_errors": errors,
            "selective_accuracy": round(float(correct[auto].mean()), 4) if n_auto else None,
            "cost": round((MISROUTE_COST * errors + held) / n, 4),
        })
    return rows


def main(argv=None) -> int:
    global MISROUTE_COST

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--misroute-cost", type=float, default=5.0)
    parser.add_argument("--write-config", action="store_true",
                        help="write the chosen thresholds to config/routing_policy.json")
    args = parser.parse_args(argv)
    MISROUTE_COST = args.misroute_cost

    configure()
    ensure_dirs()
    registry = ModelRegistry()
    if not registry.versions:
        LOGGER.error("no trained models found")
        return 1

    frame = load_split("val")
    texts, truth = frame["text"].tolist(), frame["intent"].tolist()

    results: Dict[str, object] = {
        "split": "val",
        "n_rows": len(texts),
        "misroute_cost_in_reviews": MISROUTE_COST,
        "by_version": {},
    }
    lines = [
        "<!-- GENERATED by `python -m experiments.tune_confidence_threshold` -->\n",
        "# Confidence threshold for auto-routing\n\n",
        f"Validation split, {len(texts)} records. Cost model: one wrong "
        f"auto-route costs the same as **{MISROUTE_COST:g}** manual reviews.\n\n",
    ]

    for version in registry.versions:
        model = registry.get(version)
        probabilities = model.predict_proba(texts)
        predicted = [model.labels[i] for i in probabilities.argmax(axis=1)]
        confidence = probabilities.max(axis=1)
        correct = np.array([t == p for t, p in zip(truth, predicted)])

        rows = sweep(confidence, correct)
        best = min(rows, key=lambda r: r["cost"])
        results["by_version"][version] = {"sweep": rows, "chosen": best}
        LOGGER.info("%s: threshold %.2f (cost %.4f, auto-route %.1f%%, "
                    "selective accuracy %.4f)",
                    version, best["threshold"], best["cost"],
                    100 * best["auto_route_rate"], best["selective_accuracy"] or 0)

        lines.append(f"## `{version}`\n\n")
        # selective_accuracy is None only if the threshold admits nothing, which
        # a cost-minimising choice will not do — but do not crash if it happens.
        selective = (
            "n/a" if best["selective_accuracy"] is None
            else f"{best['selective_accuracy']:.4f}"
        )
        lines.append(
            f"Chosen threshold **{best['threshold']:.2f}** — auto-routes "
            f"{best['auto_route_rate']:.1%} of records at "
            f"{selective} accuracy, holding "
            f"{best['held_for_review']} for review.\n\n"
        )
        lines.append("| Threshold | Auto-route rate | Selective accuracy | "
                     "Auto-routed errors | Held | Cost |\n")
        lines.append("| ---: | ---: | ---: | ---: | ---: | ---: |\n")
        for row in rows:
            marker = " **<-**" if row["threshold"] == best["threshold"] else ""
            accuracy = ("n/a" if row["selective_accuracy"] is None
                        else f"{row['selective_accuracy']:.4f}")
            lines.append(
                f"| {row['threshold']:.2f} | {row['auto_route_rate']:.4f} "
                f"| {accuracy} | {row['auto_routed_errors']} "
                f"| {row['held_for_review']} | {row['cost']:.4f}{marker} |\n"
            )
        lines.append("\n")

    chosen = {v: r["chosen"]["threshold"] for v, r in results["by_version"].items()}
    results["chosen_per_version"] = chosen
    spread = max(chosen.values()) - min(chosen.values()) if chosen else 0.0
    results["spread"] = round(spread, 4)

    lines.append(
        "## What the service actually uses\n\n"
        f"Per-version optima on this run: {chosen} — a spread of "
        f"**{spread:.2f}**.\n\n"
        "These are not interchangeable. The models' confidence distributions "
        "are genuinely different (mean top-1 probability on validation runs "
        "from roughly 0.79 for gradient boosting to 0.96 for the transformer), "
        "so a shared threshold would either hold back most of the linear "
        "model's correct predictions or wave through most of the transformer's "
        "wrong ones. The service therefore applies a **per-version** threshold, "
        "held in `config/routing_policy.json` and read by "
        "`RoutingPolicy.from_file`. `DEFAULT_CONFIDENCE_THRESHOLD` in "
        "`src/config.py` is only the fallback for a version with no entry.\n\n"
        "Regenerate the config from this experiment with:\n\n"
        "```bash\n"
        "python -m experiments.tune_confidence_threshold --write-config\n"
        "```\n"
    )

    (RESULTS_DIR / "confidence_threshold.json").write_text(
        json.dumps(results, indent=2), encoding="utf-8")
    (RESULTS_DIR / "confidence_threshold.md").write_text(
        "".join(lines), encoding="utf-8")
    LOGGER.info("wrote %s", RESULTS_DIR / "confidence_threshold.md")

    if args.write_config:
        existing = (
            json.loads(ROUTING_POLICY_PATH.read_text(encoding="utf-8"))
            if ROUTING_POLICY_PATH.exists() else {}
        )
        payload = {
            "_generated_by": "python -m experiments.tune_confidence_threshold --write-config",
            "_selected_on": "validation split, minimising "
                            f"{MISROUTE_COST:g}*auto_routed_errors + held_for_review",
            "confidence_threshold": min(chosen.values()) if chosen else 0.75,
            "version_thresholds": chosen,
            "strong_negative_sentiment": existing.get("strong_negative_sentiment", -0.5),
            "high_urgency": existing.get("high_urgency", 0.5),
            "max_escalation_steps": existing.get("max_escalation_steps", 2),
        }
        ROUTING_POLICY_PATH.parent.mkdir(parents=True, exist_ok=True)
        ROUTING_POLICY_PATH.write_text(json.dumps(payload, indent=2), encoding="utf-8")
        LOGGER.info("wrote %s", ROUTING_POLICY_PATH)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
